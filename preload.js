const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('orbit', {
  getConfig: () => ipcRenderer.invoke('config:get'),
  setConfig: (partial) => ipcRenderer.invoke('config:set', partial),
  login: () => ipcRenderer.invoke('accounts:login'),
  removeAccount: (id) => ipcRenderer.invoke('accounts:remove', id),
  applyFlags: (opts) => ipcRenderer.invoke('flags:apply', opts),
  previewFlags: () => ipcRenderer.invoke('flags:preview'),
  mods: {
    pickFont: () => ipcRenderer.invoke('mods:pickFont'),
    clearFont: () => ipcRenderer.invoke('mods:clearFont'),
    fontData: () => ipcRenderer.invoke('mods:fontData'),
    fontList: () => ipcRenderer.invoke('mods:fontList'),
    fontBytes: (id) => ipcRenderer.invoke('mods:fontBytes', id),
    useFont: (id) => ipcRenderer.invoke('mods:useFont', id),
    removeFont: (id) => ipcRenderer.invoke('mods:removeFont', id),
    setCursorImage: (bytes, presetId) => ipcRenderer.invoke('mods:setCursorImage', bytes, presetId),
    setEmoteImage: (baseBytes, themeId, stickerBytes) => ipcRenderer.invoke('mods:setEmoteImage', baseBytes, themeId, stickerBytes),
    pickImageFile: (title) => ipcRenderer.invoke('mods:pickImageFile', title),
    getStickers: () => ipcRenderer.invoke('mods:getStickers'),
    saveStickers: (list) => ipcRenderer.invoke('mods:saveStickers', list),
    saveEmoteBase: (bytes) => ipcRenderer.invoke('mods:saveEmoteBase', bytes),
    emoteBase: () => ipcRenderer.invoke('mods:emoteBase'),
    wheelLines: () => ipcRenderer.invoke('mods:wheelLines'),
    clearEmoteImage: () => ipcRenderer.invoke('mods:clearEmoteImage'),
    pickDeath: () => ipcRenderer.invoke('mods:pickDeath'),
    clearDeath: () => ipcRenderer.invoke('mods:clearDeath'),
    oofDeath: () => ipcRenderer.invoke('mods:oofDeath'),
    pickCharSound: (slot) => ipcRenderer.invoke('mods:pickCharSound', slot),
    setCharSound: (slot, mode) => ipcRenderer.invoke('mods:setCharSound', slot, mode),
    previews: () => ipcRenderer.invoke('mods:previews'),
  },
  status: () => ipcRenderer.invoke('roblox:status'),
  launchProgress: (since) => ipcRenderer.invoke('launch:progress', since),
  launchHold: (on) => ipcRenderer.invoke('launch:hold', on),
  focusRoblox: () => ipcRenderer.invoke('launch:focusRoblox'),
  gpuStatus: () => ipcRenderer.invoke('gpu:status'),
  playtime: () => ipcRenderer.invoke('playtime:get'),
  music: {
    state: () => ipcRenderer.invoke('music:state'),
    cmd: (c) => ipcRenderer.invoke('music:cmd', c),
    setHotkey: (action, accel) => ipcRenderer.invoke('music:setHotkey', action, accel),
    testPopup: () => ipcRenderer.invoke('music:testPopup'),
    player: (action) => ipcRenderer.invoke('music:player', action),
    learnPad: (target) => ipcRenderer.invoke('music:learnPad', target),
    clearPad: (target) => ipcRenderer.invoke('music:clearPad', target),
    onUpdate: (cb) => ipcRenderer.on('music:update', (_e, s) => cb(s)),
  },
  hasNvidiaApp: () => ipcRenderer.invoke('gpu:hasNvidiaApp'),
  openNvidiaApp: () => ipcRenderer.invoke('gpu:openNvidiaApp'),
  launch: (opts) => ipcRenderer.invoke('roblox:launch', opts),
  instances: () => ipcRenderer.invoke('instances:list'),
  kill: (pid) => ipcRenderer.invoke('instances:kill', pid),
  api: (url, opts = {}) => ipcRenderer.invoke('api', { url, ...opts }),
  openUrl: (url) => ipcRenderer.invoke('open:url', url),
  cdnGet: (url, as) => ipcRenderer.invoke('cdn:get', url, as),
  rolimons: () => ipcRenderer.invoke('rolimons:items'),
  openRobloxFolder: () => ipcRenderer.invoke('open:robloxFolder'),
  win: (action) => ipcRenderer.send('win', action),
  onKeySound: (cb) => ipcRenderer.on('keysound', (_e, d) => cb(d)),
  onGameLeft: (cb) => ipcRenderer.on('roblox:left', (_e, d) => cb(d)),
  keys: {
    list: () => ipcRenderer.invoke('keys:list'),
    bytes: (id) => ipcRenderer.invoke('keys:bytes', id),
    import: () => ipcRenderer.invoke('keys:import'),
    remove: (id) => ipcRenderer.invoke('keys:remove', id),
  },
});
